#!/usr/bin/env node
"use strict";

// ARCH-106 dry run. Reads the committed ARCH-103 baseline and decision file,
// builds the complete canonical plan, and writes the machine-readable and
// human-readable reconciliation reports. It never opens a database.

const fs = require("node:fs");
const path = require("node:path");

const { canonicalJson } = require("./baseline-lib.js");
const {
  DEFAULT_CAPTURE_ROOT,
  DEFAULT_DECISIONS_PATH,
  buildPlan,
  readDecisions,
  readSources
} = require("./migration-lib.js");

const DEFAULT_OUT_DIR = path.join("data", "migration");
const JSON_REPORT = "arch-106-reconciliation.json";
const MARKDOWN_REPORT = "arch-106-reconciliation.md";

function parseArgs(argv) {
  const options = {
    capture: DEFAULT_CAPTURE_ROOT,
    decisions: DEFAULT_DECISIONS_PATH,
    outDir: DEFAULT_OUT_DIR,
    write: true
  };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--capture") options.capture = argv[++index];
    else if (arg === "--decisions") options.decisions = argv[++index];
    else if (arg === "--out-dir") options.outDir = argv[++index];
    else if (arg === "--no-write") options.write = false;
    else throw new Error(`Unrecognised argument: ${arg}`);
  }
  return options;
}

function table(headers, rows) {
  const lines = [`| ${headers.join(" | ")} |`, `|${headers.map(() => "---").join("|")}|`];
  for (const row of rows) lines.push(`| ${row.join(" | ")} |`);
  return lines.join("\n");
}

function renderMarkdown(report) {
  const counts = report.canonicalEntityCounts;
  const sections = [];

  sections.push("# ARCH-106 migration reconciliation report");
  sections.push(
    "Generated by `npm run migrate:reconcile` from the committed ARCH-103 baseline and `data/migration/arch-106-decisions.json`. " +
    "It is a deterministic function of those two inputs and is regenerated, never hand-edited. " +
    "It does not modify the ARCH-103 capture report or manifest."
  );

  sections.push("## Status");
  sections.push(
    report.status === "READY"
      ? "**READY.** Every source discrepancy has an explicit resolution and the loader may write to a database."
      : `**BLOCKED.** ${report.blockers.length} condition(s) need an owner decision before any load. See *Blockers* below.`
  );

  sections.push("## Baseline");
  sections.push(table(["Field", "Value"], [
    ["Capture directory", `\`data/exports/${report.baseline.captureDirectory}\``],
    ["Capture timestamp", `\`${report.baseline.captureTimestamp}\``],
    ["Raw payload SHA-256", `\`${report.baseline.rawSha256}\``],
    ["Canonical payload SHA-256", `\`${report.baseline.canonicalSha256}\``]
  ]));

  sections.push("## Source rows by tab");
  sections.push(table(
    ["Tab", "Data rows"],
    Object.entries(report.sourceRowCounts).sort().map(([tab, rows]) => [`\`${tab}\``, String(rows)])
      .concat([["**Total**", `**${report.sourceRowCountsTotal}**`]])
  ));

  sections.push("## Canonical entities by table");
  sections.push(table(
    ["Canonical table or domain", "Rows"],
    Object.entries(counts).map(([name, value]) => [`\`${name}\``, String(value)])
  ));

  sections.push("## Source-to-canonical mapping");
  sections.push(table(
    ["Mapping", "Rows"],
    Object.entries(report.mappings.oneToOne).map(([name, value]) => [name, value])
  ));

  sections.push("### Many-to-one (collapsed) mappings");
  sections.push(report.mappings.manyToOne.length === 0
    ? "None applied."
    : [
      table(
        ["Mode", "Defence", "Counter", "Source rows", "Surviving row", "Resolution", "Identical duplicate?", "Retained note", "Notes dropped"],
        report.mappings.manyToOne.map((entry) => [
          entry.mode, entry.defenceDisplayName, `\`${entry.counterArchetypeCode}\``,
          entry.sourceRows.join(", "), String(entry.survivingSourceRow), `\`${entry.resolution}\``,
          entry.identicalDuplicate ? "yes" : "**no**",
          entry.retainedNote === "" ? "—" : `\`${entry.retainedNote}\``,
          String(entry.notesDropped)
        ])
      ),
      "",
      report.mappings.manyToOne.map((entry) => `- **${entry.mode} | ${entry.defenceDisplayName} | ${entry.counterArchetypeCode}** — ${entry.rationale}`).join("\n")
    ].join("\n"));

  sections.push("### Synthesized definitions");
  sections.push(report.mappings.synthesized.length === 0
    ? "None."
    : table(
      ["Archetype code", "Display name", "Provenance", "created_by"],
      report.mappings.synthesized.map((entry) => [
        `\`${entry.archetypeCode}\``, `\`${entry.displayName}\``, `\`${entry.provenance}\``, `\`${entry.createdBy}\``
      ])
    ));

  sections.push("## Defence identity resolution");
  sections.push(table(["Outcome", "Count"], [
    ["Distinct defence display names", String(report.defenceIdentities.distinctDisplayNames)],
    ["Reused an exact, unique attack identity", String(report.defenceIdentities.reusedExactAttackIdentity)],
    ["Created as a defence-only archetype", String(report.defenceIdentities.defenceOnly)]
  ]));
  sections.push("### Defence-only archetypes");
  sections.push(table(
    ["Display name (unchanged)", "Generated archetype_code", "battle_type"],
    report.defenceIdentities.defenceOnlyMappings.map((entry) => [
      `\`${entry.displayName}\``, `\`${entry.archetypeCode}\``, entry.battleType
    ])
  ));

  sections.push("## Generated internal identifiers");
  sections.push(report.generatedIdentifiers.length === 0
    ? "None."
    : [
      "Every generated identifier below comes from one deterministic rule:",
      "",
      "> `DEF_` + the display name uppercased, every character outside `[A-Z0-9]` replaced by `_`, runs of `_` collapsed, leading and trailing `_` removed. Names are processed in ascending code-point order; a collision with an already-assigned `archetype_code` takes the first free `_2`, `_3`, … suffix.",
      "",
      table(
        ["Kind", "Input", "Generated", "Collision suffix"],
        report.generatedIdentifiers.map((entry) => [
          `\`${entry.kind}\``, `\`${entry.displayName}\``, `\`${entry.generated}\``,
          entry.collisionSuffix === null ? "—" : String(entry.collisionSuffix)
        ])
      )
    ].join("\n"));

  sections.push("## Unit identifier renames");
  sections.push(report.unitIdRenames.length === 0
    ? "None. Every migrated `unit_id` is the source `Character_ID`, byte-for-byte."
    : table(
      ["Source `Character_ID`", "Canonical `unit_id`", "Source row"],
      report.unitIdRenames.map((entry) => [`\`${entry.from}\``, `\`${entry.to}\``, String(entry.sourceRow)])
    ));

  sections.push("## Note preservation");
  sections.push(table(["Measure", "Count"], [
    ["`Counters.Notes` non-blank in source", String(report.notePreservation.sourceCounterNotesNonBlank)],
    ["Non-blank notes on migrated matchups", String(report.notePreservation.migratedMatchupNotesNonBlank)],
    ["`Defence_Teams.Notes` non-blank in source", String(report.notePreservation.sourceDefenceTeamNotesNonBlank)],
    ["Non-blank migrated defence notes", String(report.notePreservation.migratedDefenceNotesNonBlank)],
    ["`GAC_Scoring.Notes` non-blank in source", String(report.notePreservation.sourceScoringNotesNonBlank)],
    ["Non-blank migrated scoring notes", String(report.notePreservation.migratedScoringNotesNonBlank)],
    ["Notes withheld with a blocked source row", String(report.notePreservation.notesWithheldByBlockers)],
    ["**Notes dropped silently**", `**${report.notePreservation.notesDroppedSilently}**`]
  ]));

  sections.push("## Required-member external-ID coverage");
  sections.push(table(["Measure", "Count"], [
    ["Distinct required attack members", String(report.requiredMemberExternalIdCoverage.distinctRequiredUnits)],
    ["Required members without an `external_id`", String(report.requiredMemberExternalIdCoverage.withoutExternalId)]
  ]));

  sections.push("## Mode normalisation");
  sections.push(report.modeNormalisations.map((line) => `- ${line}`).join("\n"));
  sections.push(
    "The database stores the canonical `gac.catalogue_mode` enum. `data/migration/arch-106-decisions.json` " +
    "→ `modeNormalisation.canonicalToPublic` is the projection ARCH-108 must apply so the published payload keeps " +
    "its exact current spelling."
  );

  sections.push("## `Defence_Composition` outcome");
  sections.push(table(["Measure", "Value"], [
    ["Optional source tab present", String(report.defenceComposition.sourceTabPresent)],
    ["Defence members invented", String(report.defenceComposition.membersInvented)],
    ["Defence profiles created", String(report.defenceComposition.defenceProfilesCreated)],
    ["All defence profiles incomplete and empty", String(report.defenceComposition.allDefenceProfilesIncomplete)]
  ]));

  sections.push("## `Score_Meanings` disposition");
  sections.push(table(["Measure", "Value"], [
    ["Source rows", String(report.scoreMeanings.sourceRows)],
    ["Disposition", `\`${report.scoreMeanings.disposition}\``],
    ["Runtime table created", String(report.scoreMeanings.runtimeTableCreated)],
    ["Enduring home", report.scoreMeanings.home]
  ]));

  sections.push("## Mirror matchups");
  sections.push(report.mirrorMatchups.length === 0
    ? "None found."
    : table(
      ["Mode", "Archetype", "Display name", "Source rows"],
      report.mirrorMatchups.map((entry) => [
        entry.mode, `\`${entry.archetypeCode}\``, `\`${entry.displayName}\``, entry.sourceRows.join(", ")
      ])
    ));

  sections.push("## Dropped source rows");
  sections.push(report.droppedSourceRows.length === 0
    ? "None. Every source row has a canonical home."
    : table(
      ["Source", "Row", "Identifier", "Reason"],
      report.droppedSourceRows.map((entry) => [
        `\`${entry.source}\``, String(entry.sourceRow), `\`${entry.identifier}\``, `\`${entry.reason}\``
      ])
    ));

  sections.push("## Assurances");
  sections.push(table(
    ["Assurance", "Value"],
    Object.entries(report.assurances).map(([name, value]) => [`\`${name}\``, String(value)])
  ));

  sections.push("## Decision status");
  sections.push(table(
    ["Anomaly", "Status", "Resolution", "Decided by"],
    report.anomalies.map((entry) => [
      `\`${entry.id}\``, entry.status,
      entry.resolution === null ? "**owner decision required**" : `\`${entry.resolution}\``,
      entry.decidedBy === null ? "ARCH-106 rule" : entry.decidedBy
    ])
  ));

  sections.push("## Blockers");
  sections.push(report.blockers.length === 0
    ? "None."
    : report.blockers.map((entry) => `- **\`${entry.anomalyId}\`** — ${entry.message}`).join("\n"));

  return `${sections.join("\n\n")}\n`;
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  const sources = readSources(options.capture);
  const decisions = readDecisions(options.decisions);
  const { reconciliation } = buildPlan(sources, decisions);

  if (options.write) {
    fs.mkdirSync(path.resolve(options.outDir), { recursive: true });
    fs.writeFileSync(path.resolve(options.outDir, JSON_REPORT), canonicalJson(reconciliation));
    fs.writeFileSync(path.resolve(options.outDir, MARKDOWN_REPORT), renderMarkdown(reconciliation));
  }

  console.log(`ARCH-106 reconciliation: ${reconciliation.status}`);
  console.log(`  Baseline: ${reconciliation.baseline.captureDirectory} (${reconciliation.baseline.captureTimestamp})`);
  console.log(`  Source rows: ${reconciliation.sourceRowCountsTotal}`);
  console.log(`  Canonical entities: ${JSON.stringify(reconciliation.canonicalEntityCounts)}`);
  console.log(`  Defence identities: ${reconciliation.defenceIdentities.reusedExactAttackIdentity} reused, ${reconciliation.defenceIdentities.defenceOnly} defence-only`);
  console.log(`  Notes dropped silently: ${reconciliation.notePreservation.notesDroppedSilently} (withheld with a blocked row: ${reconciliation.notePreservation.notesWithheldByBlockers})`);
  console.log(`  Required members without external_id: ${reconciliation.requiredMemberExternalIdCoverage.withoutExternalId}`);
  if (options.write) console.log(`  Reports: ${path.join(options.outDir, JSON_REPORT)}, ${path.join(options.outDir, MARKDOWN_REPORT)}`);

  if (reconciliation.blockers.length > 0) {
    console.error(`\n${reconciliation.blockers.length} unresolved blocker(s) require an owner decision:`);
    for (const blocker of reconciliation.blockers) {
      console.error(`  - [${blocker.anomalyId}] ${blocker.message}`);
    }
    process.exitCode = 1;
  }
}

if (require.main === module) {
  try {
    main();
  } catch (error) {
    console.error(`ARCH-106 reconciliation failed: ${error.message}`);
    process.exitCode = 1;
  }
}

module.exports = { renderMarkdown };
